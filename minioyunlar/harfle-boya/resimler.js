// Beş köşeli yıldız (cokgen noktaları)
function boyaYildiz(x, y, r) {
  const n = [];
  for (let i = 0; i < 10; i++) {
    const a = -Math.PI / 2 + (i * Math.PI) / 5;
    const u = i % 2 ? r * 0.45 : r;
    n.push([Math.round(x + Math.cos(a) * u), Math.round(y + Math.sin(a) * u)]);
  }
  return n;
}

